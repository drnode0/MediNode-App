// キーワード検索。空白区切りの全語がQ・A・keywordsのどこかに含まれるものを返す（AND条件）。
// カテゴリ指定があればそのカテゴリ内に絞る。クエリが空ならカテゴリのみで絞る。
export function searchFaq(
  entries: FaqEntry[],
  query: string,
  category: FaqCategory | null,
): FaqEntry[] {
  const scoped = category ? entries.filter((e) => e.category === category) : entries
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  if (terms.length === 0) return scoped
  return scoped.filter((e) => {
    const haystack = `${e.q} ${e.a} ${e.keywords}`.toLowerCase()
    return terms.every((t) => haystack.includes(t))
  })
}
